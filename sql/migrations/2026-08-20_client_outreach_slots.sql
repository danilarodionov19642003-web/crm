create or replace function public.staff_complete_outreach_slot(
  p_mentor_id text,
  p_date date
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  app_role text := coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '');
  actor text := lower(coalesce(auth.jwt() ->> 'email', ''));
  target_id bigint;
begin
  if auth.role() <> 'authenticated' or app_role not in ('owner', 'team') then
    raise exception 'AUTH_REQUIRED' using errcode = '42501';
  end if;
  select id into target_id
  from public.client_outreach_slots
  where mentor_id = p_mentor_id
    and scheduled_date <= p_date
    and slot_status = 'scheduled'
  -- Prefer the slot planned for the actual start date. If work started late,
  -- close the oldest overdue slot instead of leaving it hanging forever.
  order by (scheduled_date = p_date) desc, scheduled_date, id
  limit 1
  for update;
  if target_id is null then return false; end if;
  update public.client_outreach_slots
  set slot_status = 'completed', completed_at = now(), updated_at = now(), changed_by = actor
  where id = target_id;
  return true;
end;
$$;

